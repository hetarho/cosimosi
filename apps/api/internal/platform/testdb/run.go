// Package testdb gives each integration-test binary its own migrated database.
package testdb

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
)

// Run leaves the caller's database untouched. Without a configured base URL,
// existing integration tests retain their ordinary skip behavior.
func Run(tests func() int) int {
	base := os.Getenv("COSIMOSI_TEST_DATABASE_URL")
	if base == "" {
		base = os.Getenv("DATABASE_URL")
	}
	if base == "" {
		return tests()
	}
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	admin, err := pgx.Connect(ctx, base)
	if err != nil {
		fmt.Fprintln(os.Stderr, "test database connection failed:", err)
		return 1
	}
	defer func() { _ = admin.Close(context.Background()) }()
	var suffix [12]byte
	if _, err := rand.Read(suffix[:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	name := "cosimosi_test_" + hex.EncodeToString(suffix[:])
	identifier := pgx.Identifier{name}.Sanitize()
	if _, err = admin.Exec(ctx, "CREATE DATABASE "+identifier); err != nil {
		fmt.Fprintln(os.Stderr, "create isolated test database:", err)
		return 1
	}
	defer func() {
		cleanup, stop := context.WithTimeout(context.Background(), 15*time.Second)
		defer stop()
		if _, err := admin.Exec(cleanup, "DROP DATABASE "+identifier+" WITH (FORCE)"); err != nil {
			fmt.Fprintln(os.Stderr, "drop isolated test database:", err)
		}
	}()
	parsed, err := url.Parse(base)
	if err != nil || (parsed.Scheme != "postgres" && parsed.Scheme != "postgresql") {
		fmt.Fprintln(os.Stderr, "test database requires a postgres URL")
		return 1
	}
	parsed.Path = "/" + name
	query := parsed.Query()
	query.Set("search_path", "public")
	parsed.RawQuery = query.Encode()
	isolated := parsed.String()
	if err := migrate(ctx, isolated); err != nil {
		fmt.Fprintln(os.Stderr, "migrate isolated test database:", err)
		return 1
	}
	if err := os.Setenv("COSIMOSI_TEST_DATABASE_URL", isolated); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	return tests()
}

func migrate(ctx context.Context, connectionURL string) error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	for {
		if _, err := os.Stat(filepath.Join(root, "db", "migrations")); err == nil {
			break
		}
		parent := filepath.Dir(root)
		if parent == root {
			return fmt.Errorf("cannot locate API migration directory")
		}
		root = parent
	}
	connection, err := pgx.Connect(ctx, connectionURL)
	if err != nil {
		return err
	}
	defer func() { _ = connection.Close(context.Background()) }()
	files, err := filepath.Glob(filepath.Join(root, "db", "migrations", "*.sql"))
	if err != nil {
		return err
	}
	sort.Strings(files)
	_, err = connection.Exec(ctx, `CREATE TABLE goose_db_version (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now()); INSERT INTO goose_db_version(version_id,is_applied) VALUES(0,true)`, pgx.QueryExecModeSimpleProtocol)
	if err != nil {
		return err
	}
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		up := strings.SplitN(string(data), "-- +goose Down", 2)[0]
		if _, err := connection.Exec(ctx, up, pgx.QueryExecModeSimpleProtocol); err != nil {
			return fmt.Errorf("%s: %w", filepath.Base(file), err)
		}
		version, err := strconv.ParseInt(strings.SplitN(filepath.Base(file), "_", 2)[0], 10, 64)
		if err != nil {
			return err
		}
		if _, err := connection.Exec(ctx, "INSERT INTO goose_db_version(version_id,is_applied) VALUES($1,true)", version); err != nil {
			return err
		}
	}
	return nil
}
